//! Obscura Combined Proof Aggregator — Transfer + Sanctions
//!
//! This SP1 circuit recursively verifies two sub-proofs:
//!   1. **Transfer proof** — balance conservation, nullifiers, Merkle inclusion
//!   2. **Sanctions proof** — OFAC non-membership (recipient is not sanctioned)
//!
//! By aggregating both into one Groth16 proof, the rollup performs one
//! on-chain verification instead of two, halving the verification cost.
//!
//! # Stdin layout (set by the host prover)
//!
//! ```
//! Field                    Type          Source
//! ─────────────────────────────────────────────────────────────────────────
//! transfer_pv_bytes        Vec<u8>       transfer_proof.public_values.to_vec()
//! transfer_vk_hash         [u32; 8]      transfer_vk.hash_u32()
//! [SP1 proof stream]       (internal)    stdin.write_proof(transfer_proof, vk)
//!
//! sanctions_pv_bytes       Vec<u8>       sanctions_proof.public_values.to_vec()
//! sanctions_vk_hash        [u32; 8]      sanctions_vk.hash_u32()
//! [SP1 proof stream]       (internal)    stdin.write_proof(sanctions_proof, vk)
//! ```
//!
//! # Security model
//!
//! - `verify_sp1_proof(&vk_hash, &sha256(pv_bytes))` ensures:
//!   a. The sub-proof was generated by the correct circuit (vk_hash matches).
//!   b. The sub-proof commits to exactly `pv_bytes` (sha256 hash matches).
//!   c. The sub-proof is cryptographically valid (passes SP1's recursion check).
//! - Cross-circuit binding: both vk_hashes are committed to combined outputs,
//!   so the rollup can verify they match the expected circuit versions.
//!
//! # Phase 2 note
//!
//! Future extension: add Helios bridge proof as a third sub-circuit for
//! ClaimDeposit operations (Helios + Transfer + Sanctions → 1 proof).

#![no_main]
sp1_zkvm::entrypoint!(main);

mod types {
    include!("../types.rs");
}
use types::*;

use sha2::{Digest, Sha256};

/// Compute SHA-256 of a byte slice.
fn sha256(data: &[u8]) -> [u8; 32] {
    Sha256::digest(data).into()
}

/// Deserialize T from bincode bytes.
///
/// `sp1_zkvm::io::commit()` uses bincode internally, so the public values bytes
/// of any SP1 circuit are bincode-encoded. Panics on deserialization failure
/// (any failure means malformed inputs from the host — proof won't verify).
fn from_bincode<T: for<'de> serde::Deserialize<'de>>(bytes: &[u8]) -> T {
    bincode::deserialize(bytes).expect("from_bincode: deserialization failed")
}

pub fn main() {
    // ── Transfer sub-proof ─────────────────────────────────────────────────────

    // Read public values bytes committed by the transfer circuit.
    let transfer_pv_bytes: Vec<u8> = sp1_zkvm::io::read_vec();

    // Read the VK hash for the transfer circuit.
    let transfer_vk_hash: [u32; 8] = sp1_zkvm::io::read();

    // Cryptographically verify the transfer proof:
    //   SHA256(transfer_pv_bytes) must match the digest the proof committed to.
    //   This ties `transfer_pv_bytes` to the verified proof — if this passes,
    //   the bytes are authentic (produced by the transfer circuit under `transfer_vk_hash`).
    let transfer_pv_hash: [u8; 32] = sha256(&transfer_pv_bytes);
    sp1_zkvm::lib::verify::verify_sp1_proof(&transfer_vk_hash, &transfer_pv_hash);

    // Deserialize Transfer public outputs (safe: provably authentic above).
    let transfer_out: TransferPublicOutputs = from_bincode(&transfer_pv_bytes);

    // ── Sanctions sub-proof ────────────────────────────────────────────────────

    let sanctions_pv_bytes: Vec<u8> = sp1_zkvm::io::read_vec();
    let sanctions_vk_hash: [u32; 8] = sp1_zkvm::io::read();

    let sanctions_pv_hash: [u8; 32] = sha256(&sanctions_pv_bytes);
    sp1_zkvm::lib::verify::verify_sp1_proof(&sanctions_vk_hash, &sanctions_pv_hash);

    let sanctions_out: SanctionsPublicOutputs = from_bincode(&sanctions_pv_bytes);

    // ── Validity assertions ────────────────────────────────────────────────────

    // Sanctions circuit should have confirmed the recipient is clean.
    // (The sanctions circuit only commits is_clean = true when it passes;
    //  if is_clean were false the circuit would have panicked. Defensive check.)
    assert!(
        sanctions_out.is_clean,
        "combined: sanctions proof marks recipient as NOT clean"
    );

    // Sanctions proof must not be stale (> 24 hours old).
    // The rollup also checks this, but an explicit circuit-level assertion
    // provides an additional layer of freshness guarantee.
    // Note: proof_timestamp is not verified against wall-clock inside the ZK circuit
    // (zkVMs have no clock access). The rollup STF does the wall-clock check.
    // We assert it's non-zero as a basic sanity guard.
    assert!(
        sanctions_out.proof_timestamp > 0,
        "combined: sanctions proof has zero timestamp"
    );

    // Transfer must move a positive amount.
    assert!(
        transfer_out.transfer_amount > 0,
        "combined: transfer amount is zero"
    );

    // At least one input nullifier and one output commitment.
    assert!(
        !transfer_out.nullifiers.is_empty(),
        "combined: no nullifiers"
    );
    assert!(
        !transfer_out.output_commitments.is_empty(),
        "combined: no output commitments"
    );

    // ── Commit combined public outputs ─────────────────────────────────────────
    //
    // The combined outputs bind both sub-circuit VK hashes so the rollup STF
    // can verify the correct circuit versions were used.

    let combined = CombinedPublicOutputs {
        nullifiers: transfer_out.nullifiers,
        output_commitments: transfer_out.output_commitments,
        transfer_amount: transfer_out.transfer_amount,
        asset_id: transfer_out.asset_id,
        merkle_root: transfer_out.merkle_root,
        recipient_commitment: sanctions_out.recipient_commitment,
        sanctions_root: sanctions_out.sanctions_root,
        proof_timestamp: sanctions_out.proof_timestamp,
        transfer_vk_hash,
        sanctions_vk_hash,
    };

    sp1_zkvm::io::commit(&combined);
}
